import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
const url='https://future-xsus-logo-engine.onrender.com';
const token=process.env.XSUS_LOGO_SERVICE_TOKEN;
if(!token||token.length<32)throw new Error('Service token required');
const health=await fetch(url+'/health',{signal:AbortSignal.timeout(60000)});
assert.equal(health.status,200);
const requestId=randomUUID();
const payload={requestId,language:'en',prompt:'Modern technology logo for "Nova" blue white'};
const call=(body,authorized=true)=>fetch(url+'/v1/generate',{method:'POST',headers:{'content-type':'application/json',...(authorized?{authorization:'Bearer '+token}:{})},body:JSON.stringify(body),signal:AbortSignal.timeout(60000)});
assert.equal((await call(payload,false)).status,401);
const response=await call(payload);
assert.equal(response.status,200);
const result=await response.json();
assert.equal(result.requestId,requestId);
assert.equal(result.status,'generated');
assert.ok(result.kit.variants.length>=3);
assert.ok(result.kit.variants.every(v=>v.svg.startsWith('<svg')));
const review=await call({...payload,requestId:randomUUID(),prompt:'Modern logo'});
assert.equal(review.status,200);
assert.equal((await review.json()).status,'review_required');
console.log('PASS: health, authentication, triple-core generation, SVG variants, clarification gate');
