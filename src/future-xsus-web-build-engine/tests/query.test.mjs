import {test} from 'node:test';
import assert from 'node:assert/strict';
import {compileQuery,createSearchRuntime} from '../query.mjs';
const resource={name:'products',fields:{name:'string',price:'number',active:'boolean'}},owner='11111111-1111-4111-8111-111111111111';
const compile=o=>compileQuery(resource,owner,o);
test('owner scoped',()=>{const r=compile();assert.match(r.sql,/"owner_id" = \$1/);assert.equal(r.args[0],owner)});
test('default pagination',()=>assert.deepEqual(compile().args,[owner,50,0]));
test('typed filters',()=>assert.deepEqual(compile({filters:{price:20,active:true}}).args,[owner,20,true,50,0]));
test('search parameterized',()=>{const s="' OR 1=1 --";const r=compile({search:s});assert.ok(!r.sql.includes(s));assert.equal(r.args[1],s)});
test('literal search',()=>assert.match(compile({search:'%_'}).sql,/strpos/));
test('stable sorting',()=>assert.match(compile({sort:'price',direction:'desc'}).sql,/ORDER BY "price" DESC, "id" ASC/));
test('invalid sort',()=>assert.throws(()=>compile({sort:'name; DROP TABLE'})));
test('invalid filter',()=>assert.throws(()=>compile({filters:{price:'20'}})));
test('owner override rejected',()=>assert.throws(()=>compile({filters:{owner_id:owner}})));
test('limit bounded',()=>assert.throws(()=>compile({limit:101})));
test('offset bounded',()=>assert.throws(()=>compile({offset:-1})));
test('invalid owner',()=>assert.throws(()=>compileQuery(resource,'bad')));
test('runtime uses verified identity',async()=>{const r=createSearchRuntime(resource,{verifyIdentity:async()=>({id:owner}),query:async(sql,args)=>{assert.equal(args[0],owner);return {rows:[{name:'X'}]}}});assert.deepEqual(await r.list('token'),[{name:'X'}])});
test('unauthorized never queries',async()=>{const r=createSearchRuntime(resource,{verifyIdentity:async()=>null,query:async()=>{throw Error('unexpected')}});await assert.rejects(r.list('bad'),/Unauthorized/)});
