import {test} from 'node:test';
import assert from 'node:assert/strict';
import {quoteCart,prepareCheckout} from '../commerce.mjs';
const input={products:[{id:'a',priceMinor:1299,stock:5},{id:'b',priceMinor:500,stock:10}],items:[{id:'a',quantity:2},{id:'b',quantity:1}]};
test('integer total',()=>assert.equal(quoteCart(input).totalMinor,3098));
test('discount rounding',()=>assert.equal(quoteCart({...input,discountBps:1000}).discountMinor,309));
test('full discount',()=>assert.equal(quoteCart({...input,discountBps:10000}).totalMinor,0));
test('duplicate lines merged',()=>assert.equal(quoteCart({...input,items:[{id:'a',quantity:1},{id:'a',quantity:2}]}).lines[0].quantity,3));
test('combined stock checked',()=>assert.throws(()=>quoteCart({...input,items:[{id:'a',quantity:3},{id:'a',quantity:3}]}),/Insufficient stock/));
test('unknown product',()=>assert.throws(()=>quoteCart({...input,items:[{id:'x',quantity:1}]})));
test('fractional quantity rejected',()=>assert.throws(()=>quoteCart({...input,items:[{id:'a',quantity:1.5}]})));
test('negative price rejected',()=>assert.throws(()=>quoteCart({...input,products:[{id:'a',priceMinor:-1,stock:5}]})));
test('duplicate catalog rejected',()=>assert.throws(()=>quoteCart({...input,products:[input.products[0],input.products[0]]})));
test('invalid currency',()=>assert.throws(()=>quoteCart({...input,currency:'XYZ'})));
test('invalid discount',()=>assert.throws(()=>quoteCart({...input,discountBps:10001})));
test('client price ignored',()=>assert.equal(quoteCart({...input,items:[{id:'a',quantity:1,priceMinor:1}]}).totalMinor,1299));
test('checkout not executable',()=>assert.equal(prepareCheckout(input).executable,false));
test('payment not authorized',()=>assert.equal(prepareCheckout(input).paymentAuthorized,false));
test('inventory not reserved',()=>assert.equal(prepareCheckout(input).inventoryReserved,false));
test('tax and shipping not included',()=>{const r=prepareCheckout(input);assert.equal(r.taxIncluded,false);assert.equal(r.shippingIncluded,false)});
