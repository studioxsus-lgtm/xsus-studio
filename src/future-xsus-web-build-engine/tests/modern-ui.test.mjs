import {test} from 'node:test';
import assert from 'node:assert/strict';
import {createModernTheme,renderModernDashboard} from '../modern-ui.mjs';
const input={title:'Overview',links:[{path:'index.html',label:'Home',current:true}],metrics:[{label:'Revenue',value:1234}]};
for(const palette of ['ocean','forest','midnight','sand'])test('palette '+palette,()=>assert.match(createModernTheme({palette}),/--accent:/));
test('responsive layout',()=>assert.match(createModernTheme(),/@media\(max-width:700px\)/));
test('compact density',()=>assert.match(createModernTheme({density:'compact'}),/--gap:8px/));
test('motion respects preference',()=>assert.match(createModernTheme({motion:true}),/prefers-reduced-motion:no-preference/));
test('motion disabled by default',()=>assert.doesNotMatch(createModernTheme(),/transition:/));
test('unknown palette rejected',()=>assert.throws(()=>createModernTheme({palette:'constructor'})));
test('skip link',()=>assert.match(renderModernDashboard(input).html,/href="#main"/));
test('current page',()=>assert.match(renderModernDashboard(input).html,/aria-current="page"/));
test('localized navigation',()=>assert.match(renderModernDashboard({...input,language:'sq'}).html,/Navigimi/));
test('escaped title',()=>assert.match(renderModernDashboard({...input,title:'<script>'}).html,/&lt;script&gt;/));
test('unsafe link rejected',()=>assert.throws(()=>renderModernDashboard({...input,links:[{path:'javascript:alert(1)',label:'Bad'}]})));
test('invalid metric rejected',()=>assert.throws(()=>renderModernDashboard({...input,metrics:[{label:'Bad',value:Infinity}]})));
test('multiple current links rejected',()=>assert.throws(()=>renderModernDashboard({...input,links:[...input.links,{path:'other.html',label:'Other',current:true}]})));
test('static data disclosed',()=>assert.equal(renderModernDashboard(input).liveData,false));
test('review required',()=>assert.equal(renderModernDashboard(input).reviewRequired,true));
