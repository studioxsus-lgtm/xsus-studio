import {test} from 'node:test';
import assert from 'node:assert/strict';
import {planMigration,assembleFullStack} from '../fullstack.mjs';
const resources=[{name:'products',fields:{name:'string',price:'number'}},{name:'orders',fields:{paid:'boolean'}}];
test('multiple resources',()=>assert.equal(planMigration(resources).resources.length,2));
test('transaction boundaries',()=>assert.match(planMigration(resources).sql,/^BEGIN;[\s\S]+COMMIT;$/));
test('RLS enabled for each resource',()=>assert.equal(planMigration(resources).sql.match(/ENABLE ROW LEVEL SECURITY/g).length,2));
test('RLS forced',()=>assert.equal(planMigration(resources).sql.match(/FORCE ROW LEVEL SECURITY/g).length,2));
test('owner read and write policy',()=>assert.match(planMigration(resources).sql,/USING \(owner_id = auth.uid\(\)\) WITH CHECK \(owner_id = auth.uid\(\)\)/));
test('rejects duplicate resources',()=>assert.throws(()=>planMigration([resources[0],resources[0]])));
test('rejects empty resources',()=>assert.throws(()=>planMigration([])));
test('rejects unsafe identifiers',()=>assert.throws(()=>planMigration([{name:'x;drop',fields:{name:'string'}}])));
test('migration not executable',()=>assert.equal(planMigration(resources).executable,false));
const build=()=>assembleFullStack({name:'Store',type:'commerce'},{resources});
test('assembles website',()=>assert.equal(build().website.validation.valid,true));
test('plans ten routes',()=>assert.equal(build().routes.length,10));
test('excludes secrets',()=>assert.equal(build().configuration.secretsIncluded,false));
test('does not claim wired runtime',()=>assert.equal(build().integration.wired,false));
test('requires review',()=>assert.equal(build().reviewRequired,true));
test('publication disabled',()=>assert.equal(build().publicationAuthorized,false));
