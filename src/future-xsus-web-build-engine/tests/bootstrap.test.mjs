import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readRuntimeConfig,createProductionRuntime} from '../bootstrap.mjs';
const env={XSUS_FUTURE_URL:'https://future.example/interpret',XSUS_HYPER_URL:'https://hyper.example/plan'};
const options={env,verifyIdentity:async()=>({id:'user'}),getToken:async()=> 'token',fetchImpl:async()=>{throw Error('Unexpected network')}};
test('default port',()=>assert.equal(readRuntimeConfig(env).port,8080));
test('custom port',()=>assert.equal(readRuntimeConfig({...env,PORT:'9000'}).port,9000));
test('invalid port',()=>assert.throws(()=>readRuntimeConfig({...env,PORT:'65536'})));
test('invalid integer',()=>assert.throws(()=>readRuntimeConfig({...env,XSUS_MAX_JOBS:'2.5'})));
test('HTTPS only',()=>assert.throws(()=>readRuntimeConfig({...env,XSUS_HYPER_URL:'http://example.com'})));
test('missing endpoint',()=>assert.throws(()=>readRuntimeConfig({})));
test('capacity defaults adapt',()=>assert.equal(readRuntimeConfig({...env,XSUS_MAX_JOBS:'1'}).maxConcurrent,1));
test('capacity bound',()=>assert.throws(()=>readRuntimeConfig({...env,XSUS_MAX_JOBS:'1',XSUS_MAX_CONCURRENT:'2'})));
test('timeout bound',()=>assert.throws(()=>readRuntimeConfig({...env,XSUS_CORE_TIMEOUT_MS:'0'})));
test('runtime composition',()=>{const r=createProductionRuntime(options);assert.equal(r.server.listening,false);assert.equal(r.diagnostics().cores.plan.state,'closed');assert.equal(r.diagnostics().jobs.total,0)});
test('identity required',()=>assert.throws(()=>createProductionRuntime({...options,verifyIdentity:null})));
test('service token required',()=>assert.throws(()=>createProductionRuntime({...options,getToken:null})));
test('stop marks unavailable',async()=>{const r=createProductionRuntime(options);await r.stop();assert.equal(r.diagnostics().ready,false);await assert.rejects(r.start())});
test('diagnostics exclude tokens',()=>assert.doesNotMatch(JSON.stringify(createProductionRuntime(options).diagnostics()),/token/));
