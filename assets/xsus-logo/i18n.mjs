export const languages=Object.freeze(['en','fr','sq']);
export function normalizeLanguage(value){return languages.includes(value)?value:'en'}
export function translate(language,key){return Object.hasOwn(messages.en,key)?messages[normalizeLanguage(language)][key]:messages[normalizeLanguage(language)].generation_failed}
export function applyLanguage(root,language){const lang=normalizeLanguage(language);root.setAttribute('lang',lang);for(const el of root.querySelectorAll('[data-logo-i18n]'))el.textContent=translate(lang,el.dataset.logoI18n);for(const el of root.querySelectorAll('[data-logo-placeholder]'))el.setAttribute('placeholder',translate(lang,el.dataset.logoPlaceholder));for(const el of root.querySelectorAll('[data-logo-label]'))el.setAttribute('aria-label',translate(lang,el.dataset.logoLabel));return lang}
