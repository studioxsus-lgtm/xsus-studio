import {describe,it,expect} from "vitest";
import {execFileSync} from "node:child_process";
import {reviewAndroidSnapshot} from "../../src/platform/xsus-app/hyper-android-review-route.js";
const script=`
import json, hashlib
s={"project_id":"projekti-1","revision":2,"application":{"platform":"android","features":["task_management","search"]},"database":[],"security":None,"design":{"label":"Detyrë – përditësim 🚀"}}
encoded=json.dumps(s,sort_keys=True,separators=(",",":"),ensure_ascii=False).encode("utf-8")
print(json.dumps({"schema_version":"1.0","operation":"project.review","source":"future-xsus-core","destination":"hyper-xsus-core","project_id":s["project_id"],"revision":s["revision"],"snapshot_digest":hashlib.sha256(encoded).hexdigest(),"specification":s,"execution_authorized":False}))
`;
describe("Python to Hyper Android review",()=>{
 it("accepts canonical Unicode snapshot generated by Python",()=>{
 const request=JSON.parse(execFileSync("python3",["-c",script],{encoding:"utf8"}));
 expect(reviewAndroidSnapshot(request).status).toBe("accepted");
 });
 it("rejects changed Unicode snapshot",()=>{
 const request=JSON.parse(execFileSync("python3",["-c",script],{encoding:"utf8"}));
 request.specification.design.label="Ndryshuar";
 expect(()=>reviewAndroidSnapshot(request)).toThrow();
 });
});
