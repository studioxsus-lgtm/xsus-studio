"""Dispatch attempts, enforce the request deadline and retry transient failures."""

import asyncio
import logging
from dataclasses import replace
from time import time_ns
from uuid import uuid4

from ..contracts.engine import EngineIdentity, EngineInstance
from ..contracts.errors import EngineError, ErrorCode
from ..contracts.request import EngineRequest
from ..contracts.response import EngineResponse
from ..routing.request_router import RequestRouter
from .transport import EngineTransport

_LOGGER = logging.getLogger(__name__)
_DEADLINE = EngineError(ErrorCode.DEADLINE_EXCEEDED, "Request deadline expired")
_NO_ROUTE = EngineError(ErrorCode.INSTANCE_UNAVAILABLE, "No eligible engine instance is available")
_ATTEMPT_TIMEOUT = EngineError(ErrorCode.INSTANCE_TIMEOUT, "Engine attempt timed out")

ExecutionResult = EngineResponse | EngineError


class RequestExecutor:
    def __init__(
        self,
        router: RequestRouter,
        transport: EngineTransport,
        *,
        max_attempts: int = 3,
        attempt_timeout_ms: int = 10_000,
    ) -> None:
        if type(max_attempts) is not int or max_attempts <= 0:
            raise ValueError("max_attempts must be a positive integer")
        if type(attempt_timeout_ms) is not int or attempt_timeout_ms <= 0:
            raise ValueError("attempt_timeout_ms must be a positive integer")
        self._router = router
        self._transport = transport
        self._max_attempts = max_attempts
        self._attempt_timeout_seconds = attempt_timeout_ms / 1_000
        self._abandoned: set[asyncio.Task[ExecutionResult]] = set()

    async def execute(self, request: EngineRequest) -> ExecutionResult:
        """Return one engine response or a failure generated by the executor."""
        loop = asyncio.get_running_loop()
        started = loop.time()
        remaining_ns = request.deadline_unix_ms * 1_000_000 - time_ns()
        if remaining_ns <= 0:
            return _DEADLINE
        deadline = started + remaining_ns / 1_000_000_000
        tried: set[str] = set()
        pinned_engine: EngineIdentity | None = None
        last_result: ExecutionResult = _NO_ROUTE

        for attempt_number in range(self._max_attempts):
            if loop.time() >= deadline:
                return _DEADLINE
            choice = self._router.select(request, engine=pinned_engine, exclude_instance_ids=tried)
            if loop.time() >= deadline:
                return _DEADLINE
            if choice is None:
                break
            instance = choice.instance
            pinned_engine = instance.engine
            tried.add(instance.instance_id)
            attempt = request if attempt_number == 0 else replace(request, attempt_id=uuid4().hex)
            attempt_deadline = min(deadline, loop.time() + self._attempt_timeout_seconds)
            last_result = await self._invoke(instance, attempt, attempt_deadline)
            if loop.time() >= deadline:
                return _DEADLINE
            outcome = last_result.outcome if isinstance(last_result, EngineResponse) else last_result
            if not isinstance(outcome, EngineError) or not outcome.allows_alternate_instance:
                return last_result

        return last_result

    async def _invoke(
        self, instance: EngineInstance, request: EngineRequest, deadline: float
    ) -> ExecutionResult:
        loop = asyncio.get_running_loop()
        remaining = deadline - loop.time()
        if remaining <= 0:
            return _ATTEMPT_TIMEOUT
        async def dispatch() -> ExecutionResult:
            if loop.time() >= deadline:
                return _ATTEMPT_TIMEOUT
            return await self._transport.invoke(instance, request)

        task = asyncio.create_task(dispatch())
        try:
            completed, _ = await asyncio.wait((task,), timeout=remaining)
        except asyncio.CancelledError:
            self._abandon(task)
            raise
        if not completed or loop.time() >= deadline:
            self._abandon(task)
            return _ATTEMPT_TIMEOUT
        if task.cancelled():
            return EngineError(ErrorCode.CANCELLED, "Engine attempt was cancelled")
        try:
            response = task.result()
            if response is _ATTEMPT_TIMEOUT:
                return _ATTEMPT_TIMEOUT
            if not isinstance(response, EngineResponse):
                raise TypeError("Engine did not return an EngineResponse")
            response.validate_for(request, instance)
        except Exception as error:
            _LOGGER.warning("Engine attempt failed for %s (%s)", instance.instance_id, type(error).__name__)
            return EngineError(ErrorCode.INTERNAL, "Engine execution failed")
        return response

    def _abandon(self, task: asyncio.Task[ExecutionResult]) -> None:
        self._abandoned.add(task)
        task.add_done_callback(self._discard_result)
        task.cancel()

    def _discard_result(self, task: asyncio.Task[ExecutionResult]) -> None:
        self._abandoned.discard(task)
        if not task.cancelled():
            task.exception()
